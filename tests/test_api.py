"""Fast stubbed route tests plus an opt-in real-checkpoint API smoke test."""

import os
from unittest.mock import ANY, create_autospec

import pytest
from fastapi.testclient import TestClient
import torch

from app import main


class _StubModel(torch.nn.Module):
    """Keeps route tests fast while preserving the published parameter count."""

    def __init__(self) -> None:
        super().__init__()
        self.weights = torch.nn.Parameter(torch.zeros(809_984))


def _stub_runtime() -> tuple:
    return _StubModel(), object(), {"context_length": 128}, torch.device("cpu")


@pytest.fixture
def stub_client(monkeypatch):
    monkeypatch.setattr(main, "get_runtime", _stub_runtime)
    monkeypatch.setattr(main, "_startup_error", None)
    with TestClient(main.app) as test_client:
        yield test_client


def test_health_and_model_info(stub_client) -> None:
    health = stub_client.get("/health")
    assert health.status_code == 200
    assert health.json()["status"] == "ok"

    info = stub_client.get("/model-info")
    assert info.status_code == 200
    assert info.json()["model_parameters"] == 809_984
    assert info.json()["context_length"] == 128
    assert info.json()["notice"] == main.GENERATED_TEXT_NOTICE


def test_generate_and_validate_inputs(monkeypatch, stub_client) -> None:
    # Autospec enforces the exact real function signature. If the API ever
    # passes an unsupported keyword (such as the former `device=` argument),
    # this test fails before returning the canned result.
    generate_stub = create_autospec(
        main.generate_text,
        return_value="ROMEO: generated by the test stub",
    )
    monkeypatch.setattr(main, "generate_text", generate_stub)
    response = stub_client.post(
        "/generate",
        json={"prompt": "ROMEO:", "max_new_tokens": 2, "temperature": 0.8, "top_k": 40},
    )
    assert response.status_code == 200
    body = response.json()
    assert body["generated"].startswith("ROMEO:")
    assert body["notice"] == main.GENERATED_TEXT_NOTICE
    generate_stub.assert_called_once_with(
        model=ANY,
        tokenizer=ANY,
        prompt="ROMEO:",
        max_new_tokens=2,
        temperature=0.8,
        top_k=40,
        top_p=None,
        greedy=False,
    )

    assert stub_client.post("/generate", json={"prompt": ""}).status_code == 422
    assert stub_client.post("/generate", json={"prompt": "ROMEO:", "max_new_tokens": 401}).status_code == 422
    assert stub_client.post("/generate", json={"prompt": "ROMEO:", "top_k": 66}).status_code == 422


@pytest.mark.real_api
@pytest.mark.skipif(
    os.getenv("RUN_REAL_API_TEST") != "1",
    reason="CPU checkpoint smoke test is opt-in: set RUN_REAL_API_TEST=1.",
)
def test_real_checkpoint_generation_through_api() -> None:
    """Opt-in proof that the weights-only checkpoint works through the API."""

    # Reloading this module's global state is unnecessary in a fresh pytest
    # process. The TestClient lifespan loads MiniGPT once, on CPU, at startup.
    with TestClient(main.app) as real_client:
        response = real_client.post(
            "/generate",
            json={"prompt": "ROMEO:", "max_new_tokens": 20, "temperature": 0.8, "top_k": 40},
        )
    assert response.status_code == 200
    assert response.json()["generated"].startswith("ROMEO:")
